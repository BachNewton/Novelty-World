// Every sound that can play: a band seats instruments by these names, nothing
// plays that isn't here, and the Instruments tab is this catalogue, so it grows
// and shrinks with it. None imitates a real instrument, and each is named and
// described for what it does in a mix. Every one here passes the no-whine measure
// (`whine.ts`), so no chimes, bells or glass: see the rule in the project's
// `CLAUDE.md`. An instrument no band or the piano picker can reach is deleted.

export type Family = "Pianos" | "Pads" | "Leads" | "Brass" | "Low end" | "Tolls and washes" | "16-bit FM" | "Sketchbook";

export const FAMILIES: readonly Family[] = ["Pianos", "Pads", "Leads", "Brass", "Low end", "Tolls and washes", "16-bit FM", "Sketchbook"];

// What the Instruments tab plays to show off a sound that a scale and a chord
// wouldn't: without one, it gets the plain examples.
export type Showcase = "hit" | "pluck" | "bass" | "drone";

export type Instrument = (AnalogVoice | StruckVoice | FmVoice | KitVoice | SoftKitVoice) & {
  // The name a person calls it by; its key below is the same name in a band sheet's spelling.
  name: string;
  family: Family;
  description: string;
  // The notes it is made for, lowest and highest. The no-whine measure runs at the top.
  range: readonly [low: number, high: number];
  showcase?: Showcase;
};

