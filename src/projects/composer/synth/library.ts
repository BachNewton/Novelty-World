export type InstrumentId = keyof typeof LIBRARY;

export const INSTRUMENT_IDS = Object.keys(LIBRARY) as InstrumentId[];

// Every piano is struck, whichever family it sits in, so a picker swaps any of them.
export const PIANO_IDS = INSTRUMENT_IDS.filter((id) => (LIBRARY[id] as Instrument).kind === "struck");

// The band's piano, for a band with one.
export function pianoOf(band: Band): InstrumentId | undefined {
  return PIANO_IDS.find((id) => Object.values(band.chairs).flat().some((chair) => chair.instrument === id));
}

// The same band with another piano in its piano's chairs.
export function withPiano(band: Band, piano: InstrumentId): Band {
  const chairs = Object.fromEntries(Object.entries(band.chairs).map(([name, seats]) => [name, seats.map((chair) => (PIANO_IDS.includes(chair.instrument) ? { ...chair, instrument: piano } : chair))]));
  return { ...band, chairs };
}

// What a track plays on, by name, its main chair first.
export function instrumentNamesForTrack(band: Band, trackName: string): string[] {
  const chairs = (band.chairs as Partial<Band["chairs"]>)[trackName] ?? [];
  return chairs.map((chair) => LIBRARY[chair.instrument].name);
}
