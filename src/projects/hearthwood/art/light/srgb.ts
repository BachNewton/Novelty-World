/** The frame's colours as the screen shows them (sRGB) to linear light and back, for passes that work on the finished frame. */
export const SRGB_GLSL = /* glsl */ `
vec3 hwToLinear(vec3 c) {
  return mix(c / 12.92, pow((c + 0.055) / 1.055, vec3(2.4)), step(vec3(0.04045), c));
}

vec3 hwToSrgb(vec3 c) {
  c = max(c, vec3(0.0));
  return mix(c * 12.92, 1.055 * pow(c, vec3(1.0 / 2.4)) - 0.055, step(vec3(0.0031308), c));
}
`;
